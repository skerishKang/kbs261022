#!/usr/bin/env python3
"""Generate the authoritative price index used by the Worker.

Why this exists
---------------
The product catalog ships as a static file (site/data/products.js) and is not
reachable from the Cloudflare Worker. Payment amounts must nevertheless be
verified server-side, so this script snapshots every confirmed public price
into backend/data/price_index.mjs.

Rules
-----
* Only products whose price.state == "public" and price.value is a number are
  indexed. Everything else is "inquiry"/"unknown" and can NEVER be paid.
* The Worker is authoritative: it ignores client-supplied unit prices and
  rejects any mismatch instead of trusting the browser.
* Product names/brands are indexed so the ERP payload is not client-authored.

Usage
-----
    python tools/store/build_price_index.py

Regenerate whenever site/data/products.json changes. The manifest in the
output records the source sha256 so drift is detectable.
"""

from __future__ import annotations

import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "site" / "data" / "products.json"
OUT_DIR = ROOT / "backend" / "data"
OUT_MJS = OUT_DIR / "price_index.mjs"

PRICE_FIELDS = ("public",)  # only state == "public" with a numeric value


def to_int_price(value):
    """Accept 368000 / '368,000' / 368000.0 and return an int, or None."""
    if value is None:
        return None
    if isinstance(value, bool):
        return None
    if isinstance(value, (int, float)):
        return int(round(value)) if value >= 0 else None
    text = str(value).strip().replace(",", "").replace("원", "").replace(" ", "")
    if not text:
        return None
    try:
        number = float(text)
    except ValueError:
        return None
    return int(round(number)) if number >= 0 else None


def main() -> int:
    if not SOURCE.exists():
        print(f"[price-index] SOURCE NOT FOUND: {SOURCE}", file=sys.stderr)
        return 1

    raw = SOURCE.read_bytes()
    products = json.loads(raw.decode("utf-8"))
    if not isinstance(products, list):
        print("[price-index] products.json must be a JSON array", file=sys.stderr)
        return 1

    index: dict[str, dict] = {}
    counted: dict[str, int] = {}
    options_count = 0
    for product in products:
        if not isinstance(product, dict):
            continue
        price_obj = product.get("price") or {}
        state = str(price_obj.get("state") or "unknown")
        pid = str(product.get("id") or "")
        if not pid:
            continue
        if not pid:
            continue
        counted[state] = counted.get(state, 0) + 1

        if state not in PRICE_FIELDS:
            continue
        unit_price = to_int_price(price_obj.get("value"))
        if unit_price is None:
            continue

        entry = {"p": unit_price}
        name = (product.get("name") or "").strip()
        brand = (product.get("brand") or "").strip()
        if name:
            entry["n"] = name[:120]
        if brand:
            entry["b"] = brand[:60]
        if product.get("options"):
            options_count += 1
        index[pid] = entry

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    body = json.dumps(index, ensure_ascii=False, separators=(",", ":"))
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    source_sha = hashlib.sha256(raw).hexdigest()

    content = (
        "// AUTO-GENERATED by tools/store/build_price_index.py — DO NOT EDIT.\n"
        "// Source: site/data/products.json\n"
        f"// Generated: {generated}\n"
        f"// products_total: {len(products)}\n"
        f"// products_with_price: {len(index)}\n"
        f"// products_without_price: {len(products) - len(index)}\n"
        f"// source_sha256: {source_sha}\n"
        "// entry = { p: unitPriceKRW, n: productName, b: brand }\n"
        "// Products missing from this map are price-unconfirmed and can never be paid.\n"
        "export const PRICE_INDEX = " + body + ";\n"
        "\n"
        "export const PRICE_INDEX_META = "
        + json.dumps(
            {
                "source": "site/data/products.json",
                "generated_at": generated,
                "products_total": len(products),
                "products_with_price": len(index),
                "products_without_price": len(products) - len(index),
                "by_price_state": counted,
                "products_with_options": options_count,
                "source_sha256": source_sha,
            },
            ensure_ascii=False,
            separators=(",", ":"),
        )
        + ";\n"
    )

    OUT_MJS.write_text(content, encoding="utf-8")
    size_kb = round(OUT_MJS.stat().st_size / 1024, 1)
    print(f"[price-index] wrote {OUT_MJS.relative_to(ROOT)} ({size_kb} KB)")
    print(f"[price-index] total={len(products)} with_price={len(index)} states={counted}")
    if len(index) == 0:
        print("[price-index] WARNING: no product has a confirmed price", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
