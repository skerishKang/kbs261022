test('the real catalogue resolves nothing and still separates mappable paths from brand pages', () => {
  // The committed evidence is regenerated by the operator, never by a test: this
  // run writes only under .work and is then compared to the files in reports/.
  const { summary } = run('real', ['--paths', `${WORK_REL}/real/category_paths.csv`, '--aggregate', `${WORK_REL}/real/summary.json`]);
  assert.equal(summary.PRODUCTS, 4575);
  assert.equal(summary.DISTINCT_PATHS, 153);
  assert.equal(summary.CORPUS_PRESENT, false, 'the tree needs a seller token, so today there is none');
  assert.equal(summary.CORPUS_ROWS, 0);
  assert.equal(summary.LEAF_IDS_PROPOSED, 0);
  assert.equal(summary.INVENTED_LEAF_IDS, 0);
  assert.equal(summary.CONFIRMED, 0);
  assert.equal(summary.NAVER_REQUESTS, 0);
  assert.equal(summary.ACCOUNT_LOGIN, 'NO');
  assert.equal(summary.LIVE_WRITES, 0);
  assert.deepEqual(summary.PATH_KINDS, { product_classification: 109, brand_index: 43, promotion_page: 1 });
  assert.equal(summary.PRODUCTS_BY_KIND.product_classification + summary.PRODUCTS_BY_KIND.brand_index + summary.PRODUCTS_BY_KIND.promotion_page, 4575,
    'the three kinds must partition the catalogue, or rows are being lost in classification');
  assert.deepEqual(summary.STATUS_BY_PRODUCT, { unresolved: 4575 });
  assert.deepEqual(summary.REASONS_BY_PATH, { corpus_absent: 109, brand_index_path: 43, promotion_page: 1 },
    'only the 109 product paths are waiting on the corpus; a brand page stays a brand page with a tree in hand');

  // The committed table is reproducible from the prep CSV alone.
  assert.ok(fs.existsSync(path.join(WORK, 'real', 'category_paths.csv')), 'the relative repo target was not written');
  assert.ok(Buffer.compare(fs.readFileSync(COMMITTED_PATHS), fs.readFileSync(path.join(WORK, 'real', 'category_paths.csv'))) === 0,
    'the committed path table is not what the tool reproduces');
  assert.ok(Buffer.compare(fs.readFileSync(COMMITTED_AGGREGATE), fs.readFileSync(path.join(WORK, 'real', 'summary.json'))) === 0,
    'the committed aggregate is not what the tool reproduces');
  const rows = parseCsv(fs.readFileSync(COMMITTED_PATHS, 'utf8'));
  assert.equal(rows.length, 153);
  assert.deepEqual(Object.keys(rows[0]), ['category_path', 'leaf', 'path_kind', 'products', 'distinct_brands', 'brand_disagrees', 'status', 'reason', 'candidate_leaf_category_ids', 'candidate_leaf_category_names', 'candidate_scores', 'candidate_evidence', 'confirmed']);
  assert.equal(rows.reduce((sum, row) => sum + Number(row.products), 0), 4575, 'per-path counts must add back up to the catalogue');
  for (const row of rows) {
    assert.equal(row.confirmed, 'no');
    assert.equal(row.candidate_leaf_category_ids, '', 'no corpus, so no row may carry an id');
    assert.equal(row.status, 'unresolved');
  }
  const brand = rows.find((row) => row.category_path === '홈 > 브랜드별 보기 > H-K > KLOTZ');
  assert.equal(brand.path_kind, 'brand_index');
  assert.equal(brand.reason, 'brand_index_path');
  assert.equal(rows.find((row) => row.category_path === '이어폰').path_kind, 'product_classification');
});

test('the committed aggregate publishes counts, not the supplier request surface', () => {
  const text = fs.readFileSync(COMMITTED_AGGREGATE, 'utf8');
  const aggregate = JSON.parse(text);
  assert.equal(aggregate.transmitted, false);
  assert.equal(aggregate.account_login, 'NO');
  assert.equal(aggregate.naver_requests, 0);
  assert.equal(aggregate.corpus.parsed, false);
  assert.equal(aggregate.corpus.selectable_leaves, false);
  assert.equal(aggregate.corpus.file, null, 'a corpus file is only recorded when one was actually read');
  assert.equal(aggregate.census.invented_leaf_category_ids, 0);
  assert.equal(aggregate.rule, 'only path_kind=product_classification is scored against the corpus; brand_index and promotion_page are never given a leaf, and a leaf id is copied out of the corpus or not written at all');
  // Nothing here turns into a request log against the supplier.
  assert.ok(!/samamusic|samasound|samastore/i.test(text), 'the supplier host must not appear');
  assert.ok(!/https?:\/\/[^"]*\/web\/product\//i.test(text), 'no image URL may leak into the category artefact');
  assert.ok(!/[0-9a-f]{64}/.test(text), 'no probe key belongs in this file');
  assert.equal(aggregate.documented_contract.endpoints.length, 3);
  assert.equal(aggregate.exceptional_category_enum_size, 34);
  assert.equal(aggregate.certification_kind_enum_size, 7);
});

test('a corpus in hand maps product paths and still leaves brand pages alone', () => {
  const source = writeFixture('corpus', 'prep.csv', toCsv(FIXTURE_ROWS, FIXTURE_COLUMNS));
  const corpusFile = writeFixture('corpus', 'corpus.csv', toCsv(CORPUS_ROWS, CORPUS_COLUMNS));
  const { summary, dir } = run('corpus', ['--source', source, '--corpus', corpusFile, '--paths', `${WORK_REL}/corpus/paths.csv`]);
  assert.equal(summary.PRODUCTS, 5);
  assert.equal(summary.CORPUS_PRESENT, true);
  assert.equal(summary.CORPUS_ROWS, 3);
  assert.equal(summary.CORPUS_LEAVES, 2, 'only last=true rows can be selected for registration');
  assert.equal(summary.INVENTED_LEAF_IDS, 0);
  assert.equal(summary.LEAF_IDS_PROPOSED, 2, 'two product-classification paths, two proposals');
  assert.equal(summary.CONFIRMED, 0);
  assert.deepEqual(summary.PATH_KINDS, { product_classification: 2, brand_index: 2, promotion_page: 1 });

  const rows = parseCsv(fs.readFileSync(path.join(dir, 'paths.csv'), 'utf8'));
  assert.equal(rows.length, 5);
  const byPath = new Map(rows.map((row) => [row.category_path, row]));
  assert.equal(byPath.get('이어폰').candidate_leaf_category_ids, '50005167');
  assert.equal(byPath.get('홈 > 제품분류별 보기 > 스피커 > 모니터링 스피커').candidate_leaf_category_ids, '50005200');
  assert.match(byPath.get('이어폰').candidate_evidence, /leaf_name_exact/);
  for (const cgiPath of ['홈 > 브랜드별 보기 > H-K > KLOTZ', 'KLOTZ', '10% 할인 상품']) {
    assert.equal(byPath.get(cgiPath).candidate_leaf_category_ids, '', `${cgiPath} is a ${byPath.get(cgiPath).path_kind} and gets no id`);
    assert.equal(byPath.get(cgiPath).status, 'unresolved');
    assert.equal(byPath.get(cgiPath).reason, cgiPath === '10% 할인 상품' ? 'promotion_page' : 'brand_index_path',
      'a brand page is refused on structure, not on a missing corpus');
  }
  assert.equal(byPath.get('KLOTZ').path_kind, 'brand_index', 'the nav-marked brand page and the bare brand name classify alike');
  // The invariant the fail-closed guard protects: every emitted id is in the file.
  const corpusText = fs.readFileSync(path.join(ROOT, corpusFile), 'utf8');
  for (const row of rows) {
    for (const id of row.candidate_leaf_category_ids.split('|').filter(Boolean)) {
      assert.ok(corpusText.includes(id), `${id} is not a corpus id`);
    }
    assert.equal(row.confirmed, 'no');
  }
  // Provenance: the aggregate names the corpus file it actually read.
  const withAggregate = run('corpus-agg', ['--source', source, '--corpus', corpusFile, '--aggregate', `${WORK_REL}/corpus-agg/summary.json`]);
  const aggregate = JSON.parse(fs.readFileSync(path.join(WORK, 'corpus-agg', 'summary.json'), 'utf8'));
  assert.equal(aggregate.corpus.file.path, corpusFile);
  assert.equal(aggregate.corpus.file.bytes, fs.statSync(path.join(ROOT, corpusFile)).size);
  assert.equal(aggregate.corpus.census.rows, 3);
  assert.equal(aggregate.census.invented_leaf_category_ids, 0);
  assert.equal(withAggregate.summary.NAVER_REQUESTS, 0);
});

test('a tree with no selectable leaf proposes nothing', () => {
  const source = writeFixture('nonleaf', 'prep.csv', toCsv(FIXTURE_ROWS, FIXTURE_COLUMNS));
  const corpusFile = writeFixture('nonleaf', 'corpus.csv', toCsv([{ id: '50000001', wholeCategoryName: '디지털 > 음향기기', name: '음향기기', last: 'false' }], CORPUS_COLUMNS));
  const { summary } = run('nonleaf', ['--source', source, '--corpus', corpusFile, '--paths', `${WORK_REL}/nonleaf/paths.csv`]);
  assert.equal(summary.CORPUS_ROWS, 1, 'the file parsed');
  assert.equal(summary.CORPUS_LEAVES, 0);
  assert.equal(summary.CORPUS_PRESENT, false, 'a branch category is not something a product can be registered under');
  assert.equal(summary.LEAF_IDS_PROPOSED, 0);
  assert.equal(summary.INVENTED_LEAF_IDS, 0);
  assert.equal(summary.STATUS_BY_PRODUCT.unresolved, 5);
});

test('the repo-facing files cannot be redirected outside the repository, and a bad column is not a silent empty run', () => {
  const nothing = failWith([]);
  assert.equal(nothing.status, 2);
  assert.match(nothing.text, /nothing to write/);

  const escape = failWith(['--paths', '../category_escape.csv', '--aggregate', 'reports/data/naver/category_mapping_summary.json']);
  assert.equal(escape.status, 2);
  assert.match(escape.text, /--paths target escapes the repository/);
  assert.ok(!fs.existsSync(path.resolve(ROOT, '..', 'category_escape.csv')), 'the escaped file was written anyway');

  const aggregateEscape = failWith(['--aggregate', '../category_escape.json']);
  assert.equal(aggregateEscape.status, 2);
  assert.match(aggregateEscape.text, /--aggregate target escapes the repository/);

  const badColumn = failWith(['--path-column', '없는열', '--paths', `${WORK_REL}/guard/paths.csv`]);
  assert.equal(badColumn.status, 2);
  assert.match(badColumn.text, /column 없는열 is not in/);

  const missingCorpus = failWith(['--corpus', 'no/such/corpus.json', '--paths', `${WORK_REL}/guard/paths.csv`]);
  assert.notEqual(missingCorpus.status, 0, 'a named corpus that does not exist must not degrade into a corpus-absent run');
});
