const BACKEND = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const ROOT = path.resolve(BACKEND, '..');
const TOOL = path.join(BACKEND, 'tools', 'naver-category-candidates.mjs');
const WORK_REL = '.work/category-test';
const WORK = path.join(ROOT, WORK_REL);
const COMMITTED_PATHS = path.join(ROOT, 'reports', 'data', 'naver', 'category_paths.csv');
const COMMITTED_AGGREGATE = path.join(ROOT, 'reports', 'data', 'naver', 'category_mapping_summary.json');

after(() => { if (fs.existsSync(WORK)) fs.rmSync(WORK, { recursive: true, force: true }); });

const jsonFrom = (stdout) => {
  // The progress line embeds a path-kind object, so the payload is located by the
  // line that is exactly the opening brace of the pretty-printed JSON.
  const lines = stdout.split('\n');
  const start = lines.findIndex((line) => line === '{');
  assert.notEqual(start, -1, `the run printed no JSON payload:\n${stdout}`);
  return JSON.parse(lines.slice(start).join('\n'));
};

const run = (label, args = []) => {
  const dir = path.join(WORK, label);
  fs.mkdirSync(dir, { recursive: true });
  const stdout = execFileSync(process.execPath, [TOOL, ...args], { encoding: 'utf8', cwd: BACKEND });
  return { dir, stdout, summary: jsonFrom(stdout), firstLine: stdout.split('\n')[0] };
};

const failWith = (args) => {
  try {
    return { status: 0, text: execFileSync(process.execPath, [TOOL, ...args], { encoding: 'utf8', cwd: BACKEND, stdio: 'pipe' }) };
  } catch (error) {
    return { status: error.status, text: `${error.stderr || ''}${error.stdout || ''}` };
  }
};

const writeFixture = (label, name, content) => {
  const dir = path.join(WORK, label);
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, name);
  fs.writeFileSync(file, content, 'utf8');
  return path.relative(ROOT, file).replaceAll('\\', '/');
};

