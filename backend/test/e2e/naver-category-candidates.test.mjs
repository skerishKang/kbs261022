// End-to-end coverage for the category-candidate CLI. The runs are offline by
// construction: no --corpus means nothing to read but the committed prep CSV, and
// a synthetic corpus is a fixture file, not a response. The point of pinning this
// is that the artefact a reviewer sees must be exactly what the tool reproduces,
// and that a run with no tree still refuses to invent a leaf id.
//
//   node --test test/e2e/naver-category-candidates.test.mjs

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
